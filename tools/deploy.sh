#!/usr/bin/env bash
# Export the model from a FLAME checkout (read-only), publish it to the Hugging Face Hub,
# build the site pinned to that model commit, and publish the site as a static Space.
#
#   FLAME_DIR=../FLAME-main/FLAME HF_USER=Tejascodex001 tools/deploy.sh
#
# Needs: python3, uv (for the `hf` CLI), Rust + wasm-pack, Node 20+, and `hf auth login` with a write token.
set -euo pipefail
cd "$(dirname "$0")/.."

FLAME_DIR=${FLAME_DIR:-../FLAME-main/FLAME}
HF_USER=${HF_USER:?set HF_USER to your Hugging Face username}
MODEL_REPO=${MODEL_REPO:-$HF_USER/flame-tinystories-5m}
SPACE_REPO=${SPACE_REPO:-$HF_USER/flame-visualizer}
RUN=${RUN:-$FLAME_DIR/runs/tinystories-5m}
TOKENIZER=${TOKENIZER:-$FLAME_DIR/data/tokenizers/tinystories-4k.json}
hf() { uvx --from huggingface_hub hf "$@"; }

echo "1/5 parity tests against FLAME"
FLAME_DIR=$(realpath "$FLAME_DIR") cargo test --manifest-path parity/Cargo.toml --release -q

echo "2/5 export + upload model -> $MODEL_REPO"
python3 tools/export_hf.py --run "$RUN" --tokenizer "$TOKENIZER" --out hf_export --repo "$MODEL_REPO" --space "$SPACE_REPO"
hf repos create "$MODEL_REPO" --public --exist-ok >/dev/null
hf upload "$MODEL_REPO" hf_export . --commit-message "Update model export" >/dev/null
SHA=$(curl -sf "https://huggingface.co/api/models/$MODEL_REPO" | python3 -c 'import json,sys; print(json.load(sys.stdin)["sha"])')
echo "    model commit $SHA"

echo "3/5 build wasm engine + site"
(cd web && npm ci --silent && npm run wasm >/dev/null)
printf '# generated by tools/deploy.sh\nVITE_MODEL_BASE=https://huggingface.co/%s/resolve/%s/\n' "$MODEL_REPO" "$SHA" > web/.env.production
node tools/wasm_smoke.mjs hf_export
(cd web && npm run check && npm run lint && npm test && npm run build)

echo "4/5 upload site -> $SPACE_REPO"
STAGE=$(mktemp -d)
cp -r web/dist/. "$STAGE/"
sed "s|Tejascodex001/flame-tinystories-5m|$MODEL_REPO|g" hf/SPACE_README.md > "$STAGE/README.md"
hf repos create "$SPACE_REPO" --type space --sdk static --public --exist-ok >/dev/null
hf upload "$SPACE_REPO" "$STAGE" . --repo-type space --delete "assets/*" --commit-message "Deploy site (model $SHA)" >/dev/null
rm -rf "$STAGE"

HOST="https://$(echo "$SPACE_REPO" | tr '/' '-' | tr '[:upper:]' '[:lower:]').static.hf.space"
echo "5/5 end-to-end tests against $HOST"
sleep 15
(cd web && BASE_URL="$HOST" npx playwright test)
echo "done: https://huggingface.co/spaces/$SPACE_REPO"
